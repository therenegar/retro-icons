#!/usr/bin/env python3
"""Rebuild a paginated GitHub icon gallery from ICO/ and PNG/.

Run from the repository root:
    python3 update_gallery.py

Optional:
    python3 update_gallery.py --page-size 500 --include-missing
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path
from urllib.parse import quote


def natural_key(path: Path):
    return [int(x) if x.isdigit() else x.casefold()
            for x in re.split(r"(\d+)", path.name)]


def url(path: Path) -> str:
    # Encode characters that could break Markdown/HTML hrefs (spaces, #, &, etc.)
    return "/".join(quote(part, safe="-._~") for part in path.parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd(),
                        help="repository root (default: current directory)")
    parser.add_argument("--page-size", type=int, default=500)
    parser.add_argument("--include-missing", action="store_true",
                        help="include ICO entries even without corresponding PNG (broken preview)")
    args = parser.parse_args()
    if args.page_size < 1:
        parser.error("--page-size must be at least 1")

    root = args.root.resolve()
    ico_dir, png_dir = root / "ICO", root / "PNG"
    if not ico_dir.is_dir() or not png_dir.is_dir():
        parser.error("ICO/ and PNG/ folders must exist under the repository root")

    ico_files = sorted((p for p in ico_dir.iterdir()
                        if p.is_file() and p.suffix.lower() == ".ico"),
                       key=natural_key)
    png_files = sorted((p for p in png_dir.iterdir()
                        if p.is_file() and p.suffix.lower() == ".png"),
                       key=natural_key)
    png_by_stem: dict[str, Path] = {}
    for path in png_files:
        png_by_stem.setdefault(path.stem.casefold(), path)

    entries: list[str] = []
    missing = []
    for ico in ico_files:
        png = png_by_stem.get(ico.stem.casefold())
        if png is None:
            missing.append(ico.name)
            if not args.include_missing:
                continue
            png = png_dir / f"{ico.stem}.png"
        href = url(ico.relative_to(root)) + "?raw=1"
        src = url(png.relative_to(root))
        label = ico.stem.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")
        entries.append(f'<a href="{href}" title="{label}"><img src="{src}" alt="{label}" width="32" height="32"></a>')

    pages = [entries[i:i + args.page_size] for i in range(0, len(entries), args.page_size)]
    if not pages:
        pages = [[]]

    nav = " · ".join(f"[Page {i}](page{i}.md)" for i in range(1, len(pages) + 1))
    for n, page in enumerate(pages, 1):
        content = (f"# Retro Icons — Page {n} of {len(pages)}\n\n"
                   f"[Index](README.md) · {nav}\n\n"
                   + "\n".join(" ".join(page[i:i + 25]) for i in range(0, len(page), 25))
                   + f"\n\n[Index](README.md) · {nav}\n")
        (root / f"page{n}.md").write_text(content, encoding="utf-8")

    # Only delete old pageNN.md files generated by this tool, not other Markdown files.
    for path in root.glob("page*.md"):
        if re.fullmatch(r"page\d+\.md", path.name, re.IGNORECASE):
            number = int(path.stem[4:])
            if number < 1 or number > len(pages):
                path.unlink()

    readme = ["# Retro Icons", "",
              f"Browse **{len(entries):,} icons** in pages of up to {args.page_size:,}. "
              "Click any 32 × 32 preview to open its `.ICO` file.", ""]
    for n, page in enumerate(pages, 1):
        start = (n - 1) * args.page_size + 1 if page else 0
        end = start + len(page) - 1 if page else 0
        readme.append(f"- [Page {n} — icons {start:,}–{end:,}](page{n}.md)")
    readme.append("")
    (root / "README.md").write_text("\n".join(readme), encoding="utf-8")
    print(f"Found {len(ico_files):,} ICOs; published {len(entries):,} previews across {len(pages)} page(s).")
    if missing:
        print(f"Missing PNG previews ({len(missing)}):")
        for name in missing[:30]:
            print("  ", name)
        if len(missing) > 30:
            print(f"  ... and {len(missing)-30} more")
        if not args.include_missing:
            print("Missing previews were excluded; regenerate PNGs and rerun this script.")


if __name__ == "__main__":
    main()
